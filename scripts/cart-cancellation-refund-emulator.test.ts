import assert from 'node:assert/strict';
import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { fixture } from './payment-fixture.js';
import { PaymentService } from '../server/payments/service.js';
import { CancellationService } from '../server/orders/cancellation.js';
import { fulfilOrder } from '../server/orders/fulfil.js';
assert.equal(process.env.FIRESTORE_EMULATOR_HOST, '127.0.0.1:8189');
const db = getFirestore(initializeApp({ projectId: 'demo-ab-payments' }, 'cart-cancellation-local'));
const f = fixture(5); const uid = 'cart-cancellation-user';
await db.doc('products/dress').set(f.docs.get('products/dress'));
await db.doc('settings/admin').set(f.docs.get('settings/admin'));
const line = { cartItemId: 'original', product: { id: 'dress' }, selectedColor: 'Red', selectedSize: 'S', isCustomTailored: false, quantity: 2 };
await db.doc(`carts/${uid}`).set({ ownerId: uid, items: [line, { ...line, cartItemId: 'other', product: { id: 'other' } }] });
await db.doc('carts/foreign-user').set({ ownerId: 'foreign-user', items: [line] });
const payments = new PaymentService(db, f.provider); const created = await payments.create(uid, f.request); const id = created.order.id;
await Promise.all([payments.syncPayment(id, 'pay_test1', { id: 'cart-emulator-event', hash: 'same' }), payments.reconcile(id)]);
assert.equal((await db.doc(`carts/${uid}`).get()).data()!.items[0].quantity, 1);
assert.equal((await db.doc('carts/foreign-user').get()).data()!.items[0].quantity, 2);
await db.runTransaction(async tx => { const ref = db.doc(`carts/${uid}`); const snap = await tx.get(ref); tx.update(ref, { items: snap.data()!.items.map((l: any) => ({ ...l, quantity: 4 })) }); });
await payments.syncPayment(id, 'pay_test1'); assert.equal((await db.doc(`carts/${uid}`).get()).data()!.items[0].quantity, 4);
const cancellations = new CancellationService(db, f.provider, false);
await assert.rejects(cancellations.request('foreign-user', id, 'Other'), /ORDER_NOT_FOUND/);
await cancellations.request(uid, id, 'Other'); await assert.rejects(fulfilOrder(db, 'admin', id, 'Processing'), /CANCELLATION_APPROVAL_REQUIRED/);
await Promise.all([cancellations.review('admin-one', id, true, 'Approved'), cancellations.review('admin-two', id, true, 'Approved')]);
assert.equal((await db.doc(`orders/${id}`).get()).data()!.data.refund.state, 'AWAITING_ENABLEMENT');
assert.equal((await db.doc(`inventoryReservations/${id}`).get()).data()!.state, 'RESTORED');
assert.equal((await db.doc('products/dress').get()).data()!.data.stockCount, 5); assert.equal(f.refundCalls, 0);
console.log('Real Firestore Cart cleanup, duplicate capture/reconciliation, ownership, fulfilment holds, admin approval and exactly-once inventory restoration passed.');
await db.terminate();
